    // MARK: grouping and rounding

    func testGroupingIsThreeDigitsWithCommas() {
        XCTAssertEqual(JavaText.grouped(0), "0")
        XCTAssertEqual(JavaText.grouped(999), "999")
        XCTAssertEqual(JavaText.grouped(1000), "1,000")
        XCTAssertEqual(JavaText.grouped(1490), "1,490")
        XCTAssertEqual(JavaText.grouped(1234567), "1,234,567")
        XCTAssertEqual(JavaText.grouped(-5), "-5")
        XCTAssertEqual(JavaText.grouped(-1234), "-1,234")
        XCTAssertEqual(JavaText.grouped(Int(Int32.min)), "-2,147,483,648")
    }

    /// Kotlin's `roundToInt` rounds halves towards positive infinity
    func testRoundToIntRoundsHalvesUp() {
        XCTAssertEqual(JavaText.roundToInt(2.5), 3)
        XCTAssertEqual(JavaText.roundToInt(-2.5), -2, "not -3, which is what rounded() says")
        XCTAssertEqual(JavaText.roundToInt(-2.51), -3)
        XCTAssertEqual(JavaText.roundToInt(0.49999999999999994), 0)
        XCTAssertEqual(JavaText.roundToInt(1.4999), 1)
        XCTAssertEqual(JavaText.roundToInt(.nan), 0)
        XCTAssertEqual(JavaText.roundToInt(1e20), Int(Int32.max))
        XCTAssertEqual(JavaText.roundToInt(-1e20), Int(Int32.min))
        XCTAssertEqual(JavaText.roundToInt(11.5), 12)
        XCTAssertEqual(JavaText.roundToInt(8.6), 9)
    }

    /// `Math.round(x)` with a 64-bit result
    func testRoundToLongRoundsHalvesUp() {
        XCTAssertEqual(JavaText.roundToLong(12_943.6 / 10.0), 1294)
        XCTAssertEqual(JavaText.roundToLong(86.6), 87)
        XCTAssertEqual(JavaText.roundToLong(-0.5), 0)
        XCTAssertEqual(JavaText.roundToLong(2.5e12), 2_500_000_000_000)
        XCTAssertEqual(JavaText.roundToLong(.nan), 0)
    }

    /// Java rounds the shortest digits half up; C rounds the exact binary value. These are where they
    /// part, and every one was read off a JVM (JDK 21).
    func testJavaRoundsTheShortestDigitsHalfUpWhereCRoundsTheExactValue() {
        XCTAssertEqual(JavaText.fixed(0.95, 1), "1.0", "C says 0.9")
        XCTAssertEqual(JavaText.fixed(1.45, 1), "1.5", "C says 1.4")
        XCTAssertEqual(JavaText.fixed(2.05, 1), "2.1", "C says 2.0")
        XCTAssertEqual(JavaText.fixed(1.95, 1), "2.0", "C says 1.9")
        XCTAssertEqual(JavaText.fixed(0.15, 1), "0.2")
        XCTAssertEqual(JavaText.fixed(1.005, 2), "1.01", "C says 1.00")
        XCTAssertEqual(JavaText.fixed(2.675, 2), "2.68", "C says 2.67")
        XCTAssertEqual(JavaText.fixed(1.115, 2), "1.12")
        XCTAssertEqual(JavaText.fixed(0.045, 2), "0.05")
    }

    /// the cases the first version of this got right by luck: exactly representable ties
    func testExactTiesGoUp() {
        XCTAssertEqual(JavaText.fixed(58.5, 0), "59")
        XCTAssertEqual(JavaText.fixed(0.5, 0), "1")
        XCTAssertEqual(JavaText.fixed(30.25, 1), "30.3")
        XCTAssertEqual(JavaText.fixed(0.125, 2), "0.13")
        XCTAssertEqual(JavaText.fixed(2.5, 0), "3")
    }

    func testCarriesRunIntoTheWholePart() {
        XCTAssertEqual(JavaText.fixed(9.96, 1), "10.0")
        XCTAssertEqual(JavaText.fixed(9.99, 0), "10")
        XCTAssertEqual(JavaText.fixed(99.95, 1), "100.0")
        XCTAssertEqual(JavaText.fixed(0.999, 2), "1.00")
        XCTAssertEqual(JavaText.fixed(999.5, 0), "1000")
    }

    func testSignsZerosAndTheNonFinite() {
        XCTAssertEqual(JavaText.fixed(0, 1), "0.0")
        XCTAssertEqual(JavaText.fixed(-0.04, 1), "-0.0")
        XCTAssertEqual(JavaText.fixed(-0.0, 2), "-0.00")
        XCTAssertEqual(JavaText.fixed(-1.45, 1), "-1.5")
        XCTAssertEqual(JavaText.fixed(.nan, 1), "NaN")
        XCTAssertEqual(JavaText.fixed(.infinity, 1), "Infinity")
        XCTAssertEqual(JavaText.fixed(-.infinity, 1), "-Infinity")
    }

    func testVeryLargeAndVerySmallValuesStayInPlainNotation() {
        XCTAssertEqual(JavaText.fixed(1e15, 1), "1000000000000000.0")
        XCTAssertEqual(JavaText.fixed(1e-5, 6), "0.000010")
        XCTAssertEqual(JavaText.fixed(5e-324, 3), "0.000")
        XCTAssertEqual(JavaText.fixed(0.0004, 1), "0.0")
        XCTAssertEqual(JavaText.fixed(0.05, 1), "0.1")
        XCTAssertEqual(JavaText.fixed(0.04, 1), "0.0")
    }

